// Builds data.js (the Aramaic part) from the study files in c:\dev\docs\TREZUZEY\ .
// The measures and coins are written by hand in midot_data.js.
// Run: node build_data.js [path-to-TREZUZEY]
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = process.argv[2] || 'c:\\dev\\docs\\TREZUZEY';
const CHUNK = 30;

function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/^\uFEFF/, '').replace(/\r/g, '').split('\n');
}

// Splits a file into { title, lines } using "title" + "====" / "----" underline headers.
function sections(lines) {
  const out = [];
  let cur = null;
  for (let i = 0; i < lines.length; i++) {
    const next = lines[i + 1] || '';
    if (lines[i].trim() && /^[=-]{3,}\s*$/.test(next)) {
      cur = { title: lines[i].trim().replace(/^\d+\.\s*/, ''), lines: [] };
      out.push(cur);
      i++;
      continue;
    }
    if (cur) cur.lines.push(lines[i]);
  }
  return out;
}

const parts = (line) => line.split(' — ').map((s) => s.trim());
const clean = (s) => (s || '').replace(/^\((.*)\)$/, '$1').replace(/\.$/, '').trim();

// "aramit — meaning (note) — note2"
function entries(sec, { abbr = false } = {}) {
  const byAr = new Map();
  for (const line of sec.lines) {
    if (!line.includes(' — ') || /^\s/.test(line)) continue;
    const p = parts(line);
    if (p[0].includes(':') || p[0].includes('...') || p.length > 3) continue;
    let w;
    if (abbr) {
      if (p.length < 3) continue;
      w = { ar: p[0], full: p[1], he: clean(p[2]), note: '' };
    } else {
      let he = p[1] || '';
      let note = clean(p[2]);
      const m = he.match(/^(.*?)\s*\(([^()]*)\)\s*$/);
      if (m && m[1]) { he = m[1]; note = [m[2], note].filter(Boolean).join(' · '); }
      w = { ar: p[0], he: clean(he), note };
    }
    if (!w.he || w.he === w.ar) continue;
    const old = byAr.get(w.ar);
    if (old) { if (!old.he.includes(w.he)) old.he += ' / ' + w.he; continue; }
    byAr.set(w.ar, w);
  }
  return [...byAr.values()];
}

function chunked(name, words) {
  if (words.length <= CHUNK * 1.3) return [{ name, words }];
  const n = Math.ceil(words.length / CHUNK);
  const size = Math.ceil(words.length / n);
  return Array.from({ length: n }, (_, k) => ({ name: `${name} ${k + 1}`, words: words.slice(k * size, (k + 1) * size) }));
}

function groups(rel, { abbr = false, skip = [], min = 5, rename } = {}) {
  const out = [];
  for (const sec of sections(read(rel))) {
    if (skip.some((s) => sec.title.includes(s))) continue;
    const words = entries(sec, { abbr });
    const name = rename ? rename(sec.title) : sec.title;
    if (words.length >= min) out.push(...chunked(name, words));
  }
  return out;
}

const data = {
  source: 'c:\\dev\\docs\\TREZUZEY',
  milim: groups('10-aramit-milim-ktanot.txt'),
  shakla: groups('11-aramit-shakla-vetarya.txt'),
  rashei: groups('12-aramit-raashei-teivot.txt', { abbr: true, rename: () => 'ראשי תיבות' }),
  pitgamim: groups('13-aramit-pitgamim.txt'),
  dibur: groups('14-aramit-bedibur.txt'),
};

const out = path.join(__dirname, 'data.js');
fs.writeFileSync(out, `'use strict';\n// Generated by build_data.js from ${data.source} – do not edit by hand.\nconst ADATA = ${JSON.stringify(data, null, 1)};\n`, 'utf8');

